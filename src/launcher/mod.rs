/// Data disk attached to the VM (a virtio-blk device besides the rootfs, e.g. tools.img).
/// Inside the guest it maps to /dev/vdb, /dev/vdc… in `-drive` append order (the rootfs
/// is always /dev/vda).
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct DataDisk {
    pub path: PathBuf,
}

impl DataDisk {
    pub(crate) fn new(path: impl Into<PathBuf>) -> Self {
        Self { path: path.into() }
    }
}

/// Persistent memory component (DT route: arm64/riscv64 direct boot has no ACPI, and
/// QEMU nvdimm's NFIT only becomes visible with EFI boot, so a pmem-region device-tree
/// node is used to bypass it).
/// - `size`: pmem region size ("256M"), carved out of the top of guest RAM (2MiB aligned);
/// - `mem_limit`: the `mem=` value appended to the cmdline (total memory − pmem region) —
///   excludes the pmem region from the kernel's linear memory model (equivalent to the
///   x86 `memmap=nn!ss` semantics);
/// - `ram_backend`: the main memory backend file (memory-backend-file share=on); the
///   carved pmem region is thus backed by a host file — guest writes persist to disk
///   and survive across runs;
/// - `dtb`: the patched device tree (generated by cli: dumpdtb + fdtput, injecting a
///   pmem-region node at the root), passed via `-dtb` to replace the QEMU-generated one.
///
/// On the guest side, of_pmem registers a label-less nd_region → no ndctl needed,
/// /dev/pmem0 appears automatically (ZONE_DEVICE mapping, QUEUE_FLAG_DAX → fsdax
/// mountable with `mount -o dax`). x86_64 uses the ACPI/e820 route, supported separately.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct PmemSpec {
    pub size: String,
    pub mem_limit: String,
    pub ram_backend: PathBuf,
    pub dtb: PathBuf,
}

impl PmemSpec {
    pub(crate) fn new(
        size: impl Into<String>,
        mem_limit: impl Into<String>,
        ram_backend: impl Into<PathBuf>,
        dtb: impl Into<PathBuf>,
    ) -> Self {
        Self {
            size: size.into(),
            mem_limit: mem_limit.into(),
            ram_backend: ram_backend.into(),
            dtb: dtb.into(),
        }
    }
}

/// First line of `qemu-system-<arch> --version` (used for the verdict run fingerprint).
pub(crate) fn qemu_version(arch: Arch) -> Option<String> {
    let out = Command::new(arch.qemu_bin())
        .arg("--version")
        .output()
        .ok()?;
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .next()
        .map(str::to_string)
}

