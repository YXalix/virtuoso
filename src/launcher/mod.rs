//! launcher — the launcher: multi-arch matrix and the QEMU launch DSL.
//!
//! `QemuInvocation` strongly types every launch shape (KVM/TCG, NUMA, GDB stub,
//! multiple virtio-blk data disks, vfio-pci passthrough); argv is frozen on the
//! original `infra/run-qemu.sh` (the removed shell baseline) and guarded by the
//! `argv_*` unit tests in qemu/argv.rs; `QEMU=echo virtuoso shell` prints argv for
//! manual comparison. The arch matrix is defined in crate::Arch — reused by both
//! builder (cross prefixes) and cli.
//!
//! Process governance (the former guardian crate) is folded into the launcher module:
//! spawning and reaping are one lifecycle; the `guardian` module carries the process
//! group RAII, the Ctrl-C guardian, and the wall-clock watchdog.

pub(crate) mod guardian;
pub(crate) mod numa;
pub(crate) mod qemu;

